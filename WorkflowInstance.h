/**
 * @file WorkflowInstance.h
 * @brief One independent execution of a workflow definition.
 */
#ifndef TIVIDY_WORKFLOW_INSTANCE_H
#define TIVIDY_WORKFLOW_INSTANCE_H

#include "ActionHistory.h"
#include "WorkflowData.h"
#include "WorkflowOutcome.h"
#include <memory>
#include <string>

class WorkNode;
class WorkflowDefinition;
class InstanceSnapshot;

/**
 * @brief A running (or finished) process created from a WorkflowDefinition.
 *
 * GoF roles: Memento::Originator (createSnapshot/restore) and
 * Command::Receiver (commands act on its work tree, data and history).
 *
 * Ownership and isolation:
 *  - OWNS a deep clone of the definition's template tree (Prototype), so
 *    changing this instance never affects the definition or other instances.
 *  - OWNS its WorkflowData (copied from the input) and its ActionHistory.
 *  - Holds only a NON-OWNING pointer to its definition; the repository owns
 *    definitions and outlives all instances.
 */
class WorkflowInstance {
public:
    /**
     * @param id    unique instance id (normally generated by InstanceManager)
     * @param def   published definition to clone
     * @param input initial data (copied)
     * @throws InvalidOperationException if the id is empty or cloning fails
     */
    WorkflowInstance(const std::string& id, const WorkflowDefinition& def, const WorkflowData& input);
    ~WorkflowInstance();

    const std::string& getId() const { return id_; }
    const WorkflowDefinition& getDefinition() const { return *definition_; }
    std::string getDefinitionName() const;
    int getDefinitionVersion() const;

    /// Start the work tree. @throws InvalidOperationException if already started or finished.
    void start();
    bool isStarted() const { return started_; }

    /// This instance's own work tree (never the definition's template).
    WorkNode& getRoot() { return *root_; }
    const WorkNode& getRoot() const { return *root_; }
    WorkflowData& getData() { return data_; }
    const WorkflowData& getData() const { return data_; }
    ActionHistory& getHistory() { return history_; }
    const ActionHistory& getHistory() const { return history_; }

    WorkflowOutcome getOutcome() const { return outcome_; }
    bool isFinished() const { return isTerminal(outcome_); }

    /**
     * Record the final outcome. Setting the same value again is ignored.
     * @throws InvalidOperationException if the instance already has a different final outcome
     */
    void setOutcome(WorkflowOutcome outcome);

    /**
     * Point this instance at another version of the same process (used by
     * migration strategies). The work tree is not changed here.
     * @throws InvalidOperationException if @p def is unpublished or has another name
     */
    void rebindTo(const WorkflowDefinition& def);

    /// Memento: capture data, outcome and the state of every node.
    std::unique_ptr<InstanceSnapshot> createSnapshot() const;
    /// Memento: return to a previously captured state. @throws InvalidOperationException for another instance's snapshot.
    void restore(const InstanceSnapshot& snapshot);

private:
    WorkflowInstance(const WorkflowInstance&);
    WorkflowInstance& operator=(const WorkflowInstance&);

    std::string id_;
    const WorkflowDefinition* definition_;
    std::unique_ptr<WorkNode> root_;
    WorkflowData data_;
    ActionHistory history_;
    WorkflowOutcome outcome_;
    bool started_;
};

#endif